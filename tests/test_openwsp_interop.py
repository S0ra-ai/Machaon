"""Conformance tests against an edit produced by the reference implementation.

The fixture in ``tests/fixtures/openwsp_v1`` was generated by OpenWSP's own
``openwsp.edits.export_edit``.  If these tests pass, an edit written here is
byte-identical to one written there, and an edit written there is accepted here.
"""
import json
import tempfile
import unittest
from pathlib import Path

import numpy as np

from machaon.interop import openwsp as wsp

FIXTURE = Path(__file__).parent / "fixtures" / "openwsp_v1"


def _load_dir(name):
    root = FIXTURE / name
    return {p.name[: -len(".npy")]: np.load(p) for p in sorted(root.glob("*.npy"))}


class TestGoldenFixture(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.originals = _load_dir("originals")
        cls.edited = _load_dir("edited")
        cls.golden = json.loads((FIXTURE / "manifest.json").read_text())

    def test_reader_accepts_reference_edit(self):
        manifest, rebuilt = wsp.read_edit(FIXTURE, self.originals)
        self.assertEqual(manifest["edit_sha256"], self.golden["edit_sha256"])
        self.assertEqual(set(rebuilt), set(self.edited))
        for name, value in rebuilt.items():
            np.testing.assert_array_equal(
                wsp.bf16_bits(value), wsp.bf16_bits(self.edited[name]),
                err_msg="reconstruction differs for %s" % name,
            )

    def test_writer_reproduces_reference_address(self):
        with tempfile.TemporaryDirectory() as tmp:
            manifest = wsp.export_edit(
                self.originals,
                self.edited,
                tmp,
                base_model=self.golden["base_model"],
                revision=self.golden["base_revision"],
            )
            self.assertEqual(manifest["payload_sha256"], self.golden["payload_sha256"])
            self.assertEqual(manifest["edit_sha256"], self.golden["edit_sha256"])

    def test_manifest_records_match(self):
        with tempfile.TemporaryDirectory() as tmp:
            manifest = wsp.export_edit(
                self.originals, self.edited, tmp,
                base_model=self.golden["base_model"],
                revision=self.golden["base_revision"],
            )
            for key in ("format", "format_version", "changed_tensors",
                        "changed_entries_total", "base_model", "base_revision"):
                self.assertEqual(manifest[key], self.golden[key], key)
            self.assertEqual(len(manifest["tensors"]), len(self.golden["tensors"]))
            for got, want in zip(manifest["tensors"], self.golden["tensors"]):
                for key in ("name", "shape", "dtype", "form", "changed_entries",
                            "base_sha256", "edited_sha256", "submitted_file"):
                    self.assertEqual(got[key], want[key], "%s/%s" % (got["name"], key))
                self.assertAlmostEqual(got["relative_change"], want["relative_change"], places=12)

    def test_delta_matches(self):
        manifest, rebuilt = wsp.read_edit(FIXTURE, self.originals)
        deltas = wsp.delta_from_edit(manifest, rebuilt, self.originals)
        self.assertEqual(set(deltas), set(self.originals))
        for name, delta in deltas.items():
            base = wsp.bits_float32(wsp.bf16_bits(self.originals[name]))
            np.testing.assert_allclose(rebuilt[name], base + delta, atol=0)


class TestTamperDetection(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.originals = _load_dir("originals")
        cls.edited = _load_dir("edited")
        cls.manifest = json.loads((FIXTURE / "manifest.json").read_text())

    def _copy(self, tmp):
        target = Path(tmp) / "edit"
        target.mkdir()
        (target / "manifest.json").write_text(json.dumps(self.manifest))
        with np.load(FIXTURE / "edit.npz") as archive:
            arrays = {k: archive[k] for k in archive.files}
        np.savez_compressed(target / "edit.npz", **arrays)
        return target, arrays

    def test_repacking_preserves_address(self):
        with tempfile.TemporaryDirectory() as tmp:
            target, _ = self._copy(tmp)
            manifest, rebuilt = wsp.read_edit(target, self.originals)
            self.assertEqual(manifest["edit_sha256"], self.manifest["edit_sha256"])

    def test_changed_payload_value_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            target, arrays = self._copy(tmp)
            arrays["t0_val"] = arrays["t0_val"].copy()
            arrays["t0_val"][0] = (int(arrays["t0_val"][0]) + 1) & 0xFFFF
            np.savez_compressed(target / "edit.npz", **arrays)
            with self.assertRaises(wsp.EditError):
                wsp.read_edit(target, self.originals)

    def test_changed_manifest_field_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            target, _ = self._copy(tmp)
            tampered = dict(self.manifest)
            tampered["changed_entries_total"] = 999
            (target / "manifest.json").write_text(json.dumps(tampered))
            with self.assertRaises(wsp.EditError):
                wsp.read_edit(target, self.originals)

    def test_wrong_base_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            target, _ = self._copy(tmp)
            wrong = {k: v.copy() for k, v in self.originals.items()}
            first = next(iter(wrong))
            wrong[first][0, 0] += np.float32(1.0)
            with self.assertRaises(wsp.EditError):
                wsp.read_edit(target, wrong)


class TestEmptyEdit(unittest.TestCase):
    def test_identical_tensors_produce_empty_edit(self):
        rng = np.random.default_rng(3)
        base = {"w": rng.normal(size=(4, 3)).astype(np.float32)}
        with tempfile.TemporaryDirectory() as tmp:
            manifest = wsp.export_edit(base, {"w": base["w"]}, tmp)
            self.assertEqual(manifest["changed_tensors"], 0)
            self.assertEqual(manifest["changed_entries_total"], 0)
            self.assertEqual(manifest["payload_sha256"],
                             "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855")
            _, rebuilt = wsp.read_edit(tmp, base)
            self.assertEqual(rebuilt, {})


class TestBf16(unittest.TestCase):
    def test_rounding_matches_torch(self):
        try:
            import torch
        except ImportError:
            self.skipTest("torch not installed")
        vals = np.concatenate([
            np.random.default_rng(0).normal(0, 5, 20000),
            np.array([0.0, -0.0, 1.0, -1.0, 3.3895314e38, 1.00390625,
                      1.01171875, 65504.0, 1e-40], dtype=np.float32),
        ]).astype(np.float32)
        expected = torch.as_tensor(vals).contiguous().to(torch.bfloat16).view(torch.uint16).numpy()
        np.testing.assert_array_equal(wsp.bf16_bits(vals), expected)

    def test_overflow_is_refused(self):
        with np.errstate(over="ignore"):
            value = np.array([1e39], dtype=np.float32)
        with self.assertRaises(wsp.EditError):
            wsp.bf16_bits(value)

    def test_roundtrip(self):
        bits = np.array([0x3F80, 0xBF80, 0x0000, 0x7F7F], dtype="<u2")
        np.testing.assert_array_equal(wsp.bf16_bits(wsp.bits_float32(bits)), bits)


